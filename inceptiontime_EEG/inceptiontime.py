output_dir = Path("/content/inceptiontime_results")
output_dir.mkdir(parents=True, exist_ok=True)


# =========================================================
# RUN BOTH CLASSIFICATION TASKS
# =========================================================

all_results = []

cv_fold_values = data["cv_fold"].to_numpy()

for task in ["binary", "five_class"]:

    print(f"\n========== {task.upper()} ==========")

    if task == "binary":
        y = y_binary
        labels = [0, 1]
    else:
        y = y_five
        labels = [0, 1, 2, 3, 4]

    task_predictions = []

    for fold in range(5):

        print(f"\nTask: {task} | Fold: {fold}")

        # Select training and validation data
        train_mask = dev_mask & (cv_fold_values != fold)
        val_mask = dev_mask & (cv_fold_values == fold)

        X_train = X[train_mask]
        X_val = X[val_mask]

        y_train = y[train_mask]
        y_val = y[val_mask]

        # Create a fresh model for each fold
        model = create_model()

        # Train
        model.fit(X_train, y_train)

        # Predict labels and probabilities
        y_pred = model.predict(X_val)
        raw_proba = model.predict_proba(X_val)

        # Ensure probability columns match class labels
        y_proba = np.column_stack([
            raw_proba[:, np.where(model.classes_ == label)[0][0]]
            for label in labels
        ])

        # Calculate evaluation metrics
        result = evaluate_model(
            y_val, y_pred, y_proba, task
        )

        result.update({
            "task": task,
            "fold": fold,
            "epochs": EPOCHS,
            "batch_size": BATCH_SIZE
        })

        all_results.append(result)

        print(
            f"Accuracy: {result['accuracy']:.4f} | "
            f"F1: {result['f1']:.4f} | "
            f"ROC-AUC: {result['roc_auc']:.4f}"
        )

        # Save sample-level predictions and probabilities
        fold_df = pd.DataFrame({
            "row_index": data.loc[
                val_mask, "row_index"
            ].to_numpy(),
            "task": task,
            "fold": fold,
            "true_label": y_val,
            "predicted_label": y_pred
        })

        for i, label in enumerate(labels):
            fold_df[f"prob_class_{label}"] = y_proba[:, i]

        task_predictions.append(fold_df)

        # Save completed metrics after every fold
        pd.DataFrame(all_results).to_csv(
            output_dir / "inceptiontime_all_cv_results.csv",
            index=False
        )

        # Save completed probabilities after every fold
        pd.concat(
            task_predictions,
            ignore_index=True
        ).to_csv(
            output_dir / f"{task}_cv_probabilities.csv",
            index=False
        )

    # =====================================================
    # CONFUSION MATRIX FOR EACH TASK
    # =====================================================

    predictions_df = pd.concat(
        task_predictions,
        ignore_index=True
    )

    cm = confusion_matrix(
        predictions_df["true_label"],
        predictions_df["predicted_label"],
        labels=labels
    )

    # Save confusion matrix as CSV
    pd.DataFrame(
        cm,
        index=[f"Actual_{i}" for i in labels],
        columns=[f"Predicted_{i}" for i in labels]
    ).to_csv(
        output_dir / f"{task}_confusion_matrix.csv"
    )

    # Plot confusion matrix
    fig, ax = plt.subplots(figsize=(7, 6))

    disp = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=labels
    )

    disp.plot(
        ax=ax,
        cmap="Blues",
        values_format="d"
    )

    ax.set_title(
        f"InceptionTime - {task} - 5-fold CV"
    )

    plt.tight_layout()

    fig.savefig(
        output_dir / f"{task}_confusion_matrix.png",
        dpi=300,
        bbox_inches="tight"
    )

    plt.show()
    plt.close(fig)


