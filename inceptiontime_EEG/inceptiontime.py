#Set model hyperparameters
EPOCHS= 20
BATCH_SIZE = 64
N_CLASSIFIERS = 1
SEED = 6200

def create_model():
    return InceptionTimeClassifier(
        n_classifiers=N_CLASSIFIERS,
        n_epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        depth=6,
        n_filters=32,
        kernel_size=40,
        random_state=SEED,
        verbose=False
    )

#define evaluation function
def evaluate_model(y_true, y_pred, y_proba, task):

    average = "binary" if task == "binary" else "macro"

    result = {
        "accuracy": accuracy_score(y_true, y_pred),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "precision": precision_score(
            y_true, y_pred, average=average, zero_division=0
        ),
        "recall": recall_score(
            y_true, y_pred, average=average, zero_division=0
        ),
        "f1": f1_score(
            y_true, y_pred, average=average, zero_division=0
        )
    }

    if task == "binary":

        tn, fp, fn, tp = confusion_matrix(
            y_true, y_pred, labels=[0, 1]
        ).ravel()

        result["specificity"] = (
            tn / (tn + fp) if (tn + fp) > 0 else np.nan
        )

        # Probability of seizure (class 1)
        result["roc_auc"] = roc_auc_score(
            y_true, y_proba[:, 1]
        )

        # PR-AUC reported as Average Precision
        result["pr_auc"] = average_precision_score(
            y_true, y_proba[:, 1]
        )

    else:

        result["specificity"] = np.nan
        result["pr_auc"] = np.nan

        # Macro ROC-AUC, One-vs-Rest
        result["roc_auc"] = roc_auc_score(
            y_true,
            y_proba,
            labels=[0, 1, 2, 3, 4],
            multi_class="ovr",
            average="macro"
        )

    return result

